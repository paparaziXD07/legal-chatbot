-- 1. ตารางฐานข้อมูลกฎหมาย (laws)
CREATE TABLE IF NOT EXISTS laws (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cat VARCHAR(50) NOT NULL, -- 'computer' หรือ 'pdpa'
  section VARCHAR(100) NOT NULL UNIQUE, -- เช่น 'มาตรา 5' หรือ 'PDPA มาตรา 19'
  title TEXT NOT NULL,
  text TEXT NOT NULL,
  simple TEXT,
  penalty TEXT,
  keywords TEXT[] DEFAULT '{}',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. ตารางคำถามที่พบบ่อย (faqs)
CREATE TABLE IF NOT EXISTS faqs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  q TEXT NOT NULL,
  a TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. ตารางประวัติการสนทนา (chat_logs)
CREATE TABLE IF NOT EXISTS chat_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_message TEXT NOT NULL,
  bot_response TEXT NOT NULL,
  detected_intent TEXT,
  model_used VARCHAR(100) DEFAULT 'OpenThaiGPT R1 (32B Reasoning)',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

