async function seedSupabase() {
  console.log('🚀 [Seed] Starting Supabase Legal Data Seeding...');

  if (!supabase) {
    console.error('❌ Supabase client is not configured. Please specify REACT_APP_SUPABASE_URL & SUPABASE_SERVICE_ROLE_KEY in .env file.');
    process.exit(1);
  }

  try {
    const { data, error } = await supabase
      .from('laws')
      .upsert(LAWS, { onConflict: 'section' });

    if (error) {
      console.error('❌ Failed to seed Supabase database:', error.message);
    } else {
      console.log(`✅ Successfully seeded ${LAWS.length} law records into Supabase table 'laws'!`);
    }
  } catch (err) {
    console.error('❌ Unexpected error during Supabase seed:', err.message);
  }
}

seedSupabase();
